print("--- Program Mencari Nilai Maksimal ---")
angka1 = float(input("Masukkan angka pertama: "))
angka2 = float(input("Masukkan angka kedua: "))

if angka1 > angka2:
    print(f"Nilai maksimal: {angka1}")
elif angka2 > angka1:
    print(f"Nilai maksimal: {angka2}")
else:
    print("Kedua angka bernilai sama")

    
